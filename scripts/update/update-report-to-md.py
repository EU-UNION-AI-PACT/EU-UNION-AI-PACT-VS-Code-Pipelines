#!/usr/bin/env python3
import json, sys
if len(sys.argv)<2:
    print("Usage: update-report-to-md.py <summary.json>")
    sys.exit(1)

try:
    doc=json.load(open(sys.argv[1]))
    print(f"# Update Report ({doc['timestamp']})")
    print(f"Mode: {doc['mode']}\n")
    
    for s in doc["sections"]:
        print(f"## {s['name']}")
        print("```")
        print(s['body'])
        print("```\n")
        
    print("---")
    print("Generated by update-report-to-md.py")
except Exception as e:
    print(f"Error processing {sys.argv[1]}: {e}")
    sys.exit(1)
